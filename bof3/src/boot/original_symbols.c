/*
 * Original BOF3 symbols referenced by lifted code before their owning source
 * files are decompiled.  The names use the Ghidra/default address convention,
 * so the import address is encoded in the symbol name.
 *
 * Keep these as absolute assembler symbols rather than C stubs. A C stub would
 * allocate new code/data in the rebuilt ELF and hide the fact that the real
 * function or object is still external to the current source set.
 */

