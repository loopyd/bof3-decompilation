"""m2c decompiler integration: toolchain wrapper and input preparation."""

from __future__ import annotations

import re
from pathlib import Path

from harness.types.context import type_context

from ..domain.claims import (
    manifest_header_paths,
    resolve_manifest_source_for_address,
)
from ..domain.ids import FunctionId
from ..domain.layout import parse_splat_text
from ..domain.manifests import TargetManifest
from ..domain.symbols import load_target_symbols
from ..io import repo_layout
from .base import PythonScriptSubmoduleToolchain

_FUNC = re.compile(r"^func_[0-9a-fA-F]{8}$")


class M2cToolchain(PythonScriptSubmoduleToolchain):
    label = "m2c"
    submodule = "third_party/m2c"
    script = "m2c.py"

    @property
    def working_directory(self) -> Path:
        return self.root


def splat_assembly(manifest: TargetManifest, address: int) -> Path:
    """Return the Splat assembly file for one function, or fail loudly."""
    root = repo_layout().root
    directory = root / "out" / "splat" / manifest.id.value / "asm"
    expected = directory / f"func_{address:08X}.s"
    if expected.is_file():
        return expected
    for symbol in load_target_symbols(
        root, manifest.id.value, psyq_space=manifest.psyq_space
    ):
        if symbol.address == address:
            named = directory / f"{symbol.name}.s"
            if named.is_file():
                return named
            break
    raise FileNotFoundError(_missing_assembly(root, manifest, address, expected))


def _declared_function_starts(root: Path, manifest: TargetManifest) -> list[int]:
    """Function boundaries the target's Splat configuration declares."""

    splat = root / manifest.splat
    if not splat.is_file():
        return []
    try:
        layout = parse_splat_text(splat.read_text(), manifest.load_address)
    except (OSError, UnicodeError, ValueError):
        return []
    return sorted(
        boundary.virtual_start
        for boundary in layout.boundaries
        if boundary.is_function and boundary.kind == "asm"
    )


def _missing_assembly(
    root: Path, manifest: TargetManifest, address: int, expected: Path
) -> str:
    """Explain why one function has no assembly, and what would fix it.

    "Run the split first" is unactionable when the address was never declared as a
    function boundary: some payloads are data-only and carry no code at all, so no
    split will ever produce the file.
    """

    starts = _declared_function_starts(root, manifest)
    identity = f"{manifest.id.value}@0x{address:08X}"
    if starts and address in starts:
        return (
            f"Splat assembly stale for {identity}: {expected} is missing although the "
            f"configuration declares it; re-run the target's Splat split"
        )
    if not starts:
        return (
            f"{identity} has no declared function boundary: {manifest.splat} declares "
            "no asm code at all, so no split can produce it"
        )
    nearest = min(starts, key=lambda start: abs(start - address))
    return (
        f"{identity} is not a declared function boundary: {manifest.splat} declares "
        f"{len(starts)} asm function boundaries and none at this address "
        f"(nearest 0x{nearest:08X})"
    )


def context_path(function: FunctionId) -> Path:
    """Return the deterministic m2c context destination for one function."""
    return (
        repo_layout().out_dir
        / "m2ctx"
        / function.target.value
        / f"{function.address:08X}.c"
    )


def render_context(function: FunctionId, manifest: TargetManifest) -> str:
    """Render the minimal deterministic m2c context owned by one target.

    m2c consumes declarations rather than a preprocessor configuration.  The
    generated context therefore records the target-owned headers and emits
    conservative old-style declarations for target-map symbols.  It never
    imports another target's source or map.
    """

    root = repo_layout().root
    symbols = load_target_symbols(
        root, manifest.id.value, psyq_space=manifest.psyq_space
    )
    base_context = type_context(
        root,
        manifest.id.value,
        "u8 " + " ".join(symbol.name for symbol in symbols),
    )
    lines = [
        "/* Generated by bin/harness lift m2ctx; do not edit. */",
        f"/* target: {manifest.id.value}; function: 0x{function.address:08X} */",
        *base_context.rstrip().splitlines(),
        "",
    ]
    resolve_manifest_source_for_address(root, manifest, function.address)
    headers = manifest_header_paths(root, manifest)
    context_header = root / "include" / "bof3" / "context.h"
    if context_header not in headers:
        headers.append(context_header)
    for header in headers:
        if header.is_file():
            try:
                relative = header.relative_to(root).as_posix()
            except ValueError:
                relative = str(header)
            lines.append(f"/* owning declaration source: {relative} */")
    if headers:
        lines.append("")
    for symbol in symbols:
        if symbol.name.startswith("func_") or _FUNC.fullmatch(symbol.name):
            lines.append(f"extern void {symbol.name}();")
        elif symbol.name.startswith("D_"):
            lines.append(f"extern u8 {symbol.name}[];")
    return "\n".join(lines) + "\n"


def asm_label(path: Path) -> str:
    """Return the first glabel of a Splat assembly file."""
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        match = re.match(r"\s*glabel\s+(\S+)", line)
        if match:
            return match.group(1)
    raise ValueError(f"no glabel found in {path}")
